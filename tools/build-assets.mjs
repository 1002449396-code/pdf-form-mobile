// Writes assets.js: the list of files the service worker caches for offline
// use, and a VERSION hashed from their contents.
//
// RUN THIS BEFORE EVERY PUBLISH. A file added without it is missing offline;
// a file changed without it is never seen by a phone that already has the
// app, because the old cache keeps answering.
//
//     node tools/build-assets.mjs

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
// Not part of the app: development files, and the two files that must never
// be served from the cache (the worker itself, and the list it reads).
const SKIP = new Set([".git", ".github", "tools", "tests", "node_modules", "sw.js",
                      "assets.js", "CLAUDE.md", "README.md", ".gitignore", ".gitattributes",
                      ".nojekyll", "package.json"]);

function walk(dir, out) {
  for (const name of readdirSync(dir).sort()) {
    if (SKIP.has(name) || name.endsWith(".map")) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

const files = walk(ROOT, []);
const hash = createHash("sha256");
const urls = ["./"];
for (const f of files) {
  const rel = relative(ROOT, f).split(sep).join("/");
  hash.update(rel).update(readFileSync(f));
  urls.push("./" + rel.split("/").map(encodeURIComponent).join("/"));
}
const version = hash.digest("hex").slice(0, 12);
writeFileSync(join(ROOT, "assets.js"),
  "// GENERATED by tools/build-assets.mjs - do not edit.\n" +
  `self.VERSION = ${JSON.stringify(version)};\n` +
  `self.ASSETS = ${JSON.stringify(urls, null, 1)};\n`);
console.log(`assets.js: ${urls.length} files, version ${version}`);
